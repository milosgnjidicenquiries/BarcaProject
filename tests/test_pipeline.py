"""The whole pipeline on a bundle that exists: read, check, infer, write, validate, reproduce.

This is the only place the tests cross the file boundary -- ``src.data.synthetic`` writes a real
ATD, a real Smart Tagging XML and a real homography file into a temporary directory, and
``pipeline.execute`` reads them back the same way it reads the delivered match. Nothing here uses
the restricted data or the public ground truth: the reference labels are the simulator's own latent
state, which is generated by this repository and is therefore allowed to be scored against.

The graded window is patched, and that is the one thing in this file worth reading twice. The real
halves start at video frame 11185, so a fixture of a few tens of thousands of frames would contain
no graded frames at all and every run would correctly refuse to answer (exit code 6). The patch gives
this fixture a window of its own; ``tests.test_alignment`` is where the published blocks are checked.
"""

from __future__ import annotations

import json
import os
import unittest
from unittest import mock

import numpy as np

from tests import helpers as h

from src import official, pipeline, settings
from src.reporting import manifest

N_FRAMES = 40000
# (half, first, last) inclusive, in video frames -- the shape official.half_video_blocks returns.
SIM_BLOCKS = [(1, 500, 20000), (2, 24000, N_FRAMES - 1)]


def graded_here(n_frames=N_FRAMES):
    mask = np.zeros(n_frames, dtype=bool)
    for _, first, last in SIM_BLOCKS:
        mask[int(first):min(n_frames, int(last) + 1)] = True
    return mask


class PipelineTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = h.TempDir()
        cls.data_dir = cls.tmp.new()
        cls.out_dir = cls.tmp.new()
        _, paths, sim = h.simulate_to_dir(n_frames=N_FRAMES, seed=20271117,
                                          blocks=[(1, 501, 20000), (2, 24001, N_FRAMES - 1)],
                                          keep=cls.data_dir)
        cls.paths = paths
        cls.sim = sim
        with mock.patch.object(official, "half_video_blocks", lambda game=None: SIM_BLOCKS):
            cls.result = pipeline.execute(data_dir=cls.data_dir, team_name="R3P-TEST")

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    # -- the artifact -------------------------------------------------------------------------

    def test_the_run_writes_a_csv_the_official_validator_accepts(self):
        info = self.result.to_csv(self.out_dir)
        self.assertEqual(info["rows"], N_FRAMES)
        self.assertEqual(os.path.basename(info["path"]), "R3P-TEST.csv")
        result = self.result.validate(n_expected=N_FRAMES)
        self.assertTrue(result["valid"], result["reason"])
        self.assertEqual(result["round_trip"], (True, "identical"))
        # A 40000-frame fixture is not a submission length. Held to the published contract, the same
        # bytes are rejected, and the rejection names the row count -- which is the check that
        # protects a real submission from a short export.
        self.assertEqual(result["rows_match_published_video"], True)
        short = self.result.validate()
        self.assertFalse(short["valid"])
        self.assertIn("row count", short["reason"])

    def test_only_the_four_labels_appear_and_x_stays_outside_the_graded_window(self):
        labels = self.result.labels
        self.assertTrue(set(np.unique(labels).tolist()) <= {0, 1, 2, 3})
        graded = self.result.graded
        self.assertTrue(np.all(labels[~graded] == 3))
        self.assertNotIn(3, np.unique(labels[graded]).tolist())
        self.assertTrue(self.result.report["outside_graded_are_X"])

    def test_the_same_bundle_twice_produces_the_same_bytes(self):
        """Deterministic reproducibility, which is a rules requirement, not a nicety."""
        first = self.result.to_csv(self.out_dir, name="repeat_a.csv")
        with mock.patch.object(official, "half_video_blocks", lambda game=None: SIM_BLOCKS):
            again = pipeline.execute(data_dir=self.data_dir, team_name="R3P-TEST")
        second = again.to_csv(self.out_dir, name="repeat_b.csv")
        self.assertEqual(first["sha256"], second["sha256"])
        self.assertTrue(np.array_equal(self.result.labels, again.labels))

    def test_the_integrity_checks_run_and_the_only_failures_are_the_fixture_length(self):
        checks = self.result.bundle.checks
        self.assertGreater(len(checks), 10)
        self.assertTrue(all(row["status"] in ("ok", "warn", "fail") for row in checks),
                        [row["status"] for row in checks])
        failed = sorted(row["name"] for row in checks if row["status"] == "fail")
        self.assertEqual(failed, ["ATD record count (official reader)", "video frame count"],
                         "a short development fixture must fail only the length checks")
        summary = self.result.describe()["checks"]
        self.assertEqual(summary["n"], len(checks))
        self.assertEqual(len(self.result.failures()), summary["fail"])
        self.assertTrue(self.result.checks_done)
        # The bundle says what it is: generated here, not the gated recording.
        self.assertTrue(self.result.bundle.development_bundle)
        self.assertTrue(any("synthetic" in row["note"].lower() for row in checks))

    def test_the_manifest_is_json_and_names_its_artifacts(self):
        self.result.to_csv(self.out_dir)
        data, path = self.result.manifest(self.out_dir, validator={"valid": True, "reason": "test"})
        with open(path, encoding="utf-8") as handle:
            on_disk = json.load(handle)
        self.assertEqual(on_disk["team_name"], "R3P-TEST")
        self.assertEqual(on_disk["data"]["frames_read"], N_FRAMES)
        self.assertEqual(on_disk["output"]["header"], "frame,label")
        self.assertEqual(on_disk["output"]["rows"], N_FRAMES)
        self.assertTrue(on_disk["output"]["validator"]["valid"])
        self.assertTrue(on_disk["provenance"]["development_bundle"])
        self.assertIn("duration_medians_s", on_disk["model_parameters"]["decoder"])
        self.assertEqual(on_disk["data"]["graded_frames"], int(graded_here().sum()))
        self.assertTrue(os.path.isfile(data["artifacts"]["transitions"]))

    # -- what it gets right --------------------------------------------------------------------

    def test_it_answers_and_does_not_degenerate_into_one_label(self):
        counts = self.result.counts()
        graded = self.result.graded
        self.assertGreater(int(graded.sum()), 1000)
        for name in ("H", "A", "D"):
            self.assertGreater(counts[name], 0, "{} never predicted".format(name))
        share = max(counts[name] for name in ("H", "A", "D")) / float(graded.sum())
        self.assertLess(share, 0.9, "one class takes {:.2f} of the graded frames".format(share))
        spells = self.result.report["spells"]
        self.assertGreater(spells["n_possessions"], 5)
        self.assertGreater(spells["median_seconds"], 0.5)
        self.assertLess(spells["longest_seconds"], 60.0)
        # The jitter readout the run-length prior exists to police: a frame-level classifier produces
        # hundreds of sub-second "possessions", a duration-aware decoder does not.
        self.assertLess(spells["under_1s"] / float(spells["n_possessions"]), 0.2)

    def test_controlled_turnovers_are_found_against_the_simulators_latent_state(self):
        """Every real change of side that lasts at least three seconds gets a transition near it.

        The clip is the simulator's, so the turnovers are controlled: the test knows exactly how many
        there are, and how long each one runs. Tolerance is 60 frames (2.4 s), which is looser than
        the tagger's own stated accuracy and tighter than the median spell.
        """
        truth = official.pm.label_codes(np.asarray(self.sim["labels"], dtype=object))
        graded = graded_here()

        def edges(codes):
            found = np.flatnonzero(np.diff(codes) != 0) + 1
            return np.array([int(frame) for frame in found
                             if graded[frame] and graded[frame - 1]], dtype=int)

        true_edges, predicted = edges(truth), self.result.labels
        pred_edges = edges(predicted)

        boundaries = []
        for index, frame in enumerate(true_edges):
            stop = int(true_edges[index + 1]) if index + 1 < len(true_edges) else len(truth)
            if truth[frame] in (0, 1) and truth[frame - 1] in (0, 1) and stop - frame >= 75:
                boundaries.append(int(frame))
        self.assertGreater(len(boundaries), 5, "the fixture contains no turnovers to find")

        hit = sum(1 for frame in boundaries if np.any(np.abs(pred_edges - frame) <= 60))
        recall = hit / float(len(boundaries))
        self.assertGreater(recall, 0.5,
                           "recovered {}/{} controlled turnovers".format(hit, len(boundaries)))

    def test_the_official_metrics_are_computed_against_the_latent_state(self):
        result = self.result.score(gt_path=self.paths["selfcheck_gt"], bootstrap_n=0)
        self.assertFalse(result["public_window_alignment_check_only"])
        self.assertGreater(result["macro_f1"], 0.6)
        self.assertGreater(result["spell_f1_mean"], 0.4)
        self.assertGreater(result["alive_dead_f1"], 0.7)
        self.assertLess(result["fragmentation"], 3.0)
        self.assertEqual(result["n_frames"], N_FRAMES)

    def test_the_evidence_channels_all_reach_the_decoder(self):
        """Every configured weight names a channel that exists, spoke, and was standardised.

        This is the audit for the no-silent-zero rule: a weight attached to a block the evidence
        layer does not produce is a channel that never speaks, and the run looks normal from outside.
        """
        usage = self.result.report["channel_usage"]
        rows = {row["channel"]: row for row in usage["channels"]}
        features = self.result.report["features"]
        blocks, dead = features["blocks"], features["dead"]
        self.assertEqual(sorted(rows), sorted(list(blocks) + list(dead)))
        for name in blocks:
            self.assertGreater(abs(rows[name]["weight"]), 0.0, "{} has no weight".format(name))
            self.assertGreater(rows[name]["frames_used"], 0, "{} never spoke".format(name))
        for name, values in blocks.items():
            self.assertEqual(len(values), N_FRAMES, name)
        self.assertEqual(sorted(blocks), sorted(self.result.report["fused"]["standardisation"]),
                         "a weighted block was silently not standardised")

    def test_the_technical_document_reports_the_run_without_inventing_anything(self):
        """The export is rendered from the manifest, so a number can only be a number the run made."""
        info = self.result.to_csv(self.out_dir)
        result = self.result.validate(n_expected=N_FRAMES)
        text = manifest.technical_document(self.result.cfg, self.result.bundle, self.result.labels,
                                           self.result.report, csv_path=info["path"],
                                           validator=result, selfcheck=None)

        # No fabricated performance: with no scorer handed in, the document must not carry a score.
        self.assertNotIn("accuracy", text)
        self.assertNotIn("spell_f1", text)
        self.assertIn("no performance numbers", text)
        # Everything the rules ask to be inspectable is in one file.
        for needle in ("frame,label", info["sha256"], "105.3", "68.0", "S_team",
                       "argmax_path", "geometric tail", "config digest", "**PASS**"):
            self.assertIn(needle, text, needle)
        # The integrity block reproduces the real statuses rather than a green wall.
        self.assertEqual(text.count("- **fail**"), len(self.result.failures()))
        self.assertEqual(text.count("- **warn**"), len(self.result.warnings()))
        # The self-check slot stays empty until a self-check is actually run.
        self.assertIn("No ground truth was scored in this run", text)
        self.assertGreater(len(text.splitlines()), 60)


if __name__ == "__main__":
    unittest.main()
