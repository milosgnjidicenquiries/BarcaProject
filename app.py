#!/usr/bin/env python
"""R3P inspection dashboard. Read-only, by construction.

    python -m streamlit run app.py

What is here: the integrity of whatever is in the data directory, a run with live progress, the
timeline and the H/A/D distribution, every transition the decoder made with how sure it was there,
the submission writer and the organizers' validator, and a one-page technical document generated from
the run's own numbers.

What is deliberately not here: any way to edit a label, a prediction, a tracking row or a tag. The
rules permit charts and video inspection for understanding and debugging, and forbid turning visual
observations into frame-specific labels or corrections -- so the dashboard shows where the model is
unsure and stops there. The frame numbers it prints are the same ones a video player takes, which is
the point of showing them.

`app.py` imports streamlit lazily enough that `python -m py_compile app.py` works without it
installed; running the dashboard needs streamlit (see requirements-r3p.txt).
"""

from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd
import streamlit as st

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

from src import official, pipeline, settings  # noqa: E402
from src.reporting import manifest, submission, summary  # noqa: E402

LABEL_COLOURS = {"H": "#1f77b4", "A": "#d62728", "D": "#7f7f7f", "X": "#ffffff"}
DEFAULT_TEAM = "MilosG"


# ---------------------------------------------------------------------------------------------
# state
# ---------------------------------------------------------------------------------------------

@st.cache_resource(show_spinner=False)
def cached_run(data_dir, team_name, source, config_path):
    """One run per (data dir, team, source, config). Re-running means changing one of those."""
    holder = {"bar": None, "text": None}

    def note(done, total, message):
        if holder["bar"] is not None and total:
            holder["bar"].progress(min(done / float(total), 1.0), text="{} · {}".format(
                message, int(done)))
        if holder["text"] is not None:
            holder["text"].write("`{}` — {}/{}".format(message, int(done), int(total)))

    cfg = settings.resolve(settings.load_config(config_path), data_dir=data_dir,
                           team_name=team_name, source=source)
    holder["bar"] = PROGRESS
    holder["text"] = LOG
    return pipeline.execute(data_dir=data_dir, team_name=team_name, source=source, cfg=cfg,
                            progress=note)


def describe_data(data_dir, source):
    """Which of the delivered files are actually present. Cheaper than a load, and it is the first
    thing a person needs to know when a run refuses to start."""
    try:
        paths = official.asset_paths(official.GAME, data_dir, source)
    except Exception as error:                                    # noqa: BLE001 - reported, not raised
        return {}, str(error)
    return {name: os.path.isfile(path) for name, path in paths.items()}, None


# ---------------------------------------------------------------------------------------------
# page
# ---------------------------------------------------------------------------------------------

st.set_page_config(page_title="R3P possession model", layout="wide", initial_sidebar_state="expanded")

with st.sidebar:
    st.title("R3P")
    st.caption("Reliability-weighted · Restart-aware · Run-length-regularized")
    data_dir = st.text_input("data directory", value="data")
    source = st.selectbox("source", sorted(official.SOURCES),
                          index=0 if official.DEFAULT_SOURCE not in official.SOURCES
                          else list(sorted(official.SOURCES)).index(official.DEFAULT_SOURCE))
    team_name = st.text_input("team name", value=DEFAULT_TEAM)
    config_path = st.text_input("config", value=os.path.join("config", "r3p.toml"))
    st.divider()
    run_button = st.button("Run R3P", type="primary", use_container_width=True)
    st.caption("The run is deterministic: the same bundle and config give the same bytes.")

st.header("1 · Integrity of the input")
present, path_error = describe_data(data_dir, source)
if path_error:
    st.error(path_error)
missing = [name for name, ok in present.items() if not ok]
cols = st.columns(max(len(present), 1))
for column, (name, ok) in zip(cols, sorted(present.items())):
    (st.success if ok else st.warning)(name)
if missing:
    st.info(
        "`{}` is not in this directory. The match assets are gated by the organizers (see `DATA.md`): "
        "unpack the bundle you were given, or point the sidebar at a development fixture generated by "
        "`python -m src.data.synthetic`.".format(", ".join(missing)))

PROGRESS = st.progress(0.0, text="idle")
LOG = st.empty()

if run_button:
    try:
        run = cached_run(data_dir, team_name, source, config_path)
    except (IOError, OSError) as error:
        st.error(str(error))
        st.stop()
    st.cache_resource.clear()          # so the next press really re-runs, and the bar restarts
else:
    run = None

if run is None:
    st.subheader("Nothing has been run yet")
    st.markdown(
        "Press **Run R3P**. The stages are read → integrity → evidence → decode → write → validate, "
        "and each one prints into this page. Output goes to `out/<TEAM>.csv`, which is git-ignored: "
        "a set of labels for the match is derived data and must not be published.")
    with st.expander("What the model will do, in the code's own terms"):
        cfg = settings.resolve(settings.load_config(config_path), data_dir=data_dir,
                               team_name=team_name, source=source)
        st.markdown(
            "- **A** fuse seven channels — {}\n- **B** dead-ball cues with signed weights — {}\n"
            "- **C** duration medians in seconds — {}".format(
                ", ".join("{} ({:+.2f})".format(name, float(weight))
                          for name, weight in cfg["fusion"]["weights"].items()),
                ", ".join("{} ({:+.2f})".format(name, float(cfg["deadball"][
                    key])) for name, key in (
                    ("static", "static_weight"), ("moving", "-alive_motion_weight"),
                    ("out of play", "oob_weight"), ("missing", "missing_weight"),
                    ("collapse", "motion_collapse_weight"), ("set piece", "tagging_weight"),
                    ("wall", "wall_weight"))),
                ", ".join("{} ≈ {}".format(name, cfg["decoder"]["duration"][name]["median_s"])
                          for name in ("H", "A", "D"))))
    st.stop()

report = run.report
arrays = report["arrays"]
labels = run.labels
graded = run.graded

# ---------------------------------------------------------------------------------------------

st.header("2 · What the run says about itself")
stats = run.describe()
c1, c2, c3, c4, c5 = st.columns(5)
c1.metric("frames", "{:,}".format(stats["n_frames"]), "graded {:,}".format(stats["graded_frames"]))
c2.metric("possessions", report["spells"]["n_possessions"],
          "median {:.2f} s".format(report["spells"]["median_seconds"] or 0.0))
c3.metric("transitions", report["n_transitions"],
          "{:,} dead-ball frames".format(report["spells"].get("dead_frames") or 0))
c4.metric("temperature", "{:.2f}".format(report["temperature"]), "solved on unlabelled frames")
c5.metric("integrity", "{} fail / {} warn".format(stats["checks"]["fail"], stats["checks"]["warn"]),
          "of {} checks".format(stats["checks"]["n"]), delta_color="off")
if stats["development_bundle"]:
    st.warning("This is a **development bundle** (generated by `src/data/synthetic.py`). Everything "
               "on this page is a code-correctness check, never a competition result.")

with st.expander("Integrity table ({} checks)".format(len(run.bundle.checks))):
    checks = pd.DataFrame(run.bundle.checks)
    st.dataframe(checks[["name", "status", "expected", "observed", "note"]],
                 use_container_width=True, hide_index=True,
                 column_config={"status": st.column_config.TextColumn("status", width="small")})

with st.expander("The algorithm, as this run actually used it"):
    st.markdown(
        "**A — reliability-weighted fusion.** Distances are metres under the real pitch metric "
        "`d = sqrt((105.3·dx)² + (68.0·dy)²)`; each channel is centred by its own median and scaled "
        "by its MAD over graded frames only, then clipped to ±4 and weighted. The fused score is "
        "damped by per-frame reliability ρ (ball gap, players seen, ghost tracklets) and divided by a "
        "temperature solved on the unlabelled match. No channel is counted twice: the dead-ball cues "
        "never enter the team score, and the continuity channel reads *observations*, never previous "
        "predictions.\n\n"
        "**B — dead ball and team, separately.** `P(D) = σ(z_dead)`, `P(H) = (1 − P(D))·q`, "
        "`P(A) = (1 − P(D))·(1 − q)`. A travelling ball enters `z_dead` with a **minus** sign, and a "
        "missing ball is the weakest of the four dead cues, because the ball is unobserved on 41 % of "
        "graded frames including deep inside live play.\n\n"
        "**C — duration-aware decoding.** An exact semi-Markov Viterbi over (label, run-age) maximises "
        "`Σ log emission + Σ log transition + Σ log p(duration)` per half, with log-normal run priors "
        "and a geometric tail, plus restart-aware entry from a stoppage. Hysteresis is the prior, not "
        "a window; genuine short spells still win when the evidence pays for `log p(d)`.")
    st.dataframe(pd.DataFrame(report["channel_usage"]["channels"]), use_container_width=True,
                 hide_index=True)
    st.caption("Standardisation is per channel and estimated from the unlabelled match: "
               "{}".format(", ".join("{}: median {:+.2f} MAD {:.2f}".format(
                   name, row["median"] or 0.0, row["mad"] or 0.0)
                   for name, row in report["standardisation"].items())))

st.header("3 · Timeline and distribution")
frames = report["label_table"]
left, right = st.columns([2, 1])
with left:
    centre = int(st.slider("window centre (video frame)", 0, max(len(labels) - 1, 1),
                           value=int(min(len(labels) // 2, 20000)), step=25))
    width = int(st.select_slider("window length", options=[250, 500, 1000, 2500, 5000], value=1000))
    start = max(0, centre - width // 2)
    stop = min(len(labels), start + width)
    st.markdown("**H** blue · **A** red · **D** grey · **X** white")
    strip = "".join(
        '<span style="display:inline-block;width:{:.2f}%;height:26px;background:{}" '
        'title="frame {} · {}"></span>'.format(100.0 / min(width, 400), LABEL_COLOURS[name],
                                               frame, name)
        for frame, name in zip(range(start, stop),
                              submission.codes_to_names(labels[start:stop])))
    st.markdown('<div style="white-space:nowrap;overflow:hidden;border:1px solid #888">'
                + strip + "</div>", unsafe_allow_html=True)
    st.caption("frames {:,}–{:,} of {:,} · {:.0f} s at {:.0f} fps — the video seek target of a frame "
               "is `frame / fps`".format(start, stop, len(labels), width / run.bundle.fps,
                                         run.bundle.fps))
    transitions = [row for row in report["transitions"]
                   if start <= row["frame"] < stop]
    if transitions:
        st.dataframe(pd.DataFrame(transitions), use_container_width=True, hide_index=True)
    else:
        st.caption("no transition inside this window")
with right:
    table = pd.DataFrame(report["label_table"]).set_index("label")
    st.bar_chart(table[["graded_frames"]].rename(columns={"graded_frames": "graded frames"}))
    st.dataframe(table, use_container_width=True)
    alive = report["spells"]
    st.metric("home share of alive time",
              "{:.1f} %".format(100.0 * (alive["home_share_of_alive"] or 0.0)))
    st.caption("{:.0f} possessions under 1 s, {:.0f} under 2 s — the jitter readout the run-length "
               "prior exists to police.".format(alive["under_1s"], alive["under_2s"]))

with st.expander("Duration histogram of predicted spells (seconds)"):
    spells = summary.spell_table(labels, graded, run.bundle.fps)
    if spells:
        seconds = pd.Series([row["seconds"] for row in spells])
        st.bar_chart(seconds.value_counts(bins=20).sort_index())
        st.dataframe(pd.DataFrame(spells[:40]), use_container_width=True, hide_index=True)
        st.caption("first 40 of {} spells".format(len(spells)))

st.header("4 · Uncertainty")
per_frame = pd.DataFrame({"frame": np.arange(len(labels))[graded],
                          "margin_nats": arrays["separation"][graded]})
st.bar_chart(per_frame["margin_nats"].value_counts(bins=25).sort_index())
st.dataframe(pd.DataFrame(report["uncertainty"]), use_container_width=True, hide_index=True)
st.caption("`margin_nats` is the gap between the best and second-best state in the Viterbi lattice at "
           "that frame. Small values are where a human glance is worth most — and the rules allow "
           "that glance to change the model, never the data.")

st.header("5 · Submission")
written = st.session_state.get("csv_path")
c1, c2 = st.columns([1, 1])
with c1:
    if st.button("Write out/{}.csv".format(team_name or DEFAULT_TEAM)):
        st.session_state["csv_path"] = run.to_csv()["path"]
    with st.expander("What the writer guarantees"):
        st.markdown("header `frame,label` · one row per video frame from 0 · only H/A/D/X · no index "
                    "column · no blanks · LF newlines on every platform · refuses to write a frame it "
                    "has no answer for")
with c2:
    path = st.session_state.get("csv_path")
    if not path:
        st.info("not written yet")
    elif st.button("Validate with the organizers' validator"):
        result = run.validate(path)
        if result["valid"]:
            st.success("PASS · {:,} rows · sha256 `{}`".format(result["rows_written"],
                                                              result["sha256"][:16]))
        else:
            st.error("FAIL · {}".format(result["reason"]))
        st.json(result)
    elif os.path.isfile(path):
        st.write("`{}`".format(os.path.relpath(path, official.ROOT).replace(os.sep, "/")))
        st.caption("then: `python evaluation/validate_submission.py {}`".format(path))

st.header("6 · Technical document")
if st.button("Generate the one-page run document"):
    text = manifest.technical_document(run.cfg, run.bundle, labels, report,
                                       st.session_state.get("csv_path"))
    st.download_button("download R3P_run_document.md", text.encode("utf-8"),
                       file_name="R3P_run_document.md", mime="text/markdown")
    st.markdown(text)
