"""Data integrity checks, run before anything is computed and shown in the dashboard.

Each check is a claim the delivered bundle is supposed to satisfy, taken from DATA.md or from
``games.py`` -- and each is falsifiable from the files alone. They exist because the failure modes
here are silent: an off-by-one in the frame join costs a few spellF1 points and produces no error,
and indexing the broadcast recording instead of the tactical one produces a 164,488-row file that
looks like a submission until it is rejected.

Statuses are ``ok`` / ``warn`` / ``fail``. ``warn`` means the data disagrees with the published
figure rather than with a hard contract -- e.g. a ball-visibility rate that is not 56.9%. That is
not a bug to fix, it is a change of input to notice, and the run manifest records it either way.
"""

from __future__ import annotations

import json
import os

import numpy as np

from .. import official

SYNTHETIC_MARKER = "SYNTHETIC_BUNDLE.json"
PUBLISHED = {
    "ball_visible_fraction_tactical": 0.569,
    "ball_visible_fraction_graded": 0.593,
    "mean_tracked_objects_during_play": 20.5,
    "track_slots": 46,
    "n_smart_tagging_instances": 638,
    "median_reprojection_error_play": 0.24,
}


def check(name, expected, observed, ok, note="", fail=False):
    """``warn`` = the data differs from a published figure; ``fail`` = the contract is broken.

    Worth separating: a ball-visibility rate that is not 56.9% means the input changed and R3P
    should say so loudly, whereas a tracking record count that is not the video length means any
    CSV built from it would be rejected by the scorer, so the run should stop.
    """
    status = "ok" if ok else ("fail" if fail else "warn")
    return {"name": name, "expected": expected, "observed": observed,
            "status": status, "note": note}


def run_integrity(tracking, tagging, homography, data_dir=None, source="tactical",
                  game=official.GAME):
    """Every check for one source. Returns (rows, n_fail, n_warn)."""
    rows = []
    n_frames = official.source_frames(source)

    synthetic_path = os.path.join(data_dir or "", SYNTHETIC_MARKER)
    if os.path.isfile(synthetic_path):
        with open(synthetic_path) as handle:
            marker = json.load(handle)
        rows.append(check(
            "bundle origin", "gated match assets", "SYNTHETIC development bundle", False,
            "This directory was generated by src/data/synthetic.py. R3P output computed from it "
            "is a correctness check of the code, never a competition result. {}".format(
                marker.get("note", ""))))

    # -- the contract every submission is written against --------------------------------------
    rows.append(check("video frame count", n_frames, tracking.anomalies["n_frames"],
                      n_frames == tracking.anomalies["n_frames"],
                      "rows of the submission CSV", fail=True))

    raw_official = official.official_atd.check_alignment_raw(data_dir=data_dir, source=source)
    rows.append(check("ATD record count (official reader)", raw_official["n_video_frames"],
                      raw_official["n_records"], bool(raw_official["agrees"]),
                      "frame_id {}..{}".format(*raw_official["frame_id_range"]), fail=True))
    first_id, last_id = raw_official["frame_id_range"]
    rows.append(check("ATD frame ids contiguous from 1", True, raw_official["contiguous"],
                      bool(raw_official["contiguous"]) and first_id == 1,
                      "video_frame = frame_id - 1, per starter/load_atd.py", fail=True))
    rows.append(check("loader agrees with official alignment check",
                      raw_official["n_records"], tracking.anomalies["lines"],
                      raw_official["n_records"] == tracking.anomalies["lines"],
                      "streaming parser vs starter check"))
    rows.append(check("frames with no tracking record", 0,
                      tracking.anomalies["frames_missing_from_tracking"],
                      tracking.anomalies["frames_missing_from_tracking"] == 0,
                      "these become X-by-absence if they exist"))
    rows.append(check("ragged ATD lines", 0, tracking.anomalies["ragged_lines"],
                      tracking.anomalies["ragged_lines"] == 0,
                      "fell back to per-line parsing that many times"))

    # -- what the tracking actually describes ---------------------------------------------------
    home = int(np.sum(tracking.team_of_slot == official.official_baseline.HOME))
    away = int(np.sum(tracking.team_of_slot == official.official_baseline.AWAY))
    rows.append(check("track slots", PUBLISHED["track_slots"], tracking.n_slots,
                      tracking.n_slots == PUBLISHED["track_slots"],
                      "slots are tracklets, not players (DATA.md)"))
    rows.append(check("team map covers every slot", tracking.n_slots, home + away,
                      home + away == tracking.n_slots,
                      "home {} / away {}".format(home, away), fail=True))
    names = official.team_names(tracking.paths["atd_meta"])
    rows.append(check("two teams named in metadata", 2, len(names), len(names) == 2,
                      "H = {}, A = {}".format(*names), fail=True))

    visible = (~np.isnan(tracking.px)).sum(axis=1)
    during = visible[visible >= 5]
    rows.append(check("mean tracked objects during play",
                      PUBLISHED["mean_tracked_objects_during_play"], round(float(during.mean()), 2)
                      if during.size else None,
                      bool(during.size) and 12.0 <= float(during.mean()) <= 30.0,
                      "occasionally exceeds 22 when the tracker duplicates someone"))
    ball_fraction = float(np.mean(tracking.ball_visible))
    rows.append(check("ball visible (all frames)", PUBLISHED["ball_visible_fraction_tactical"],
                      round(ball_fraction, 4),
                      abs(ball_fraction - PUBLISHED["ball_visible_fraction_tactical"]) < 0.05,
                      "the missing 41% is the design constraint, not an obstacle"))

    # -- homography -----------------------------------------------------------------------------
    if homography is not None:
        summary = homography.summary()
        rows.append(check("homography one row per video frame", True,
                          summary["one_row_per_video_frame"],
                          bool(summary["one_row_per_video_frame"])))
        rows.append(check("homography valid fraction", 1.0 if source == "tactical" else 0.658,
                          round(summary["valid_fraction"], 4),
                          summary["valid_fraction"] > 0.5,
                          "invalid rows carry a NaN matrix"))

    # -- smart tagging --------------------------------------------------------------------------
    if tagging is not None:
        rows.append(check("Smart Tagging time base", True, tagging.meta["agrees"],
                          bool(tagging.meta["agrees"]),
                          "tagged kickoffs contain the published kickoff frames"))
        rows.append(check("Smart Tagging instances", PUBLISHED["n_smart_tagging_instances"],
                          len(tagging.events), len(tagging.events) > 0,
                          "phases, not possessions -- never copied across as labels"))

    # -- half boundaries ------------------------------------------------------------------------
    blocks = official.half_video_blocks(game)
    graded = np.zeros(n_frames, dtype=bool)
    for _, first, last in blocks:
        graded[max(0, first):min(n_frames, last + 1)] = True
    rows.append(check("graded blocks (video frames)", "[(11185, 90651), (110808, 190197)]",
                      [(int(a), int(b)) for _, a, b in blocks],
                      len(blocks) == 2,
                      "{} graded frames of {}".format(int(graded.sum()), n_frames)))
    if homography is not None and graded.any():
        # The file is allowed to be the wrong length -- that is one of the things being checked --
        # so compare on the overlap rather than assuming it.
        overlap = min(len(homography.error), n_frames)
        inside = graded[:overlap]
        error = homography.error[:overlap]
        in_play = float(np.nanmedian(error[inside])) if inside.any() else np.nan
        out_of_play = float(np.nanmedian(error[~inside])) if (~inside).any() else np.nan
        rows.append(check("reprojection error, play vs break", "play much lower (0.24 vs ~1.5)",
                          [round(in_play, 3), round(out_of_play, 3)],
                          np.isfinite(in_play) and np.isfinite(out_of_play)
                          and in_play < out_of_play,
                          "an independent read on the published half boundaries"))

    n_fail = sum(1 for row in rows if row["status"] == "fail")
    n_warn = sum(1 for row in rows if row["status"] == "warn")
    return rows, n_fail, n_warn


def is_development_bundle(data_dir):
    return os.path.isfile(os.path.join(data_dir or "", SYNTHETIC_MARKER))
